async function seedArticles() {
  const existing = await sdk.crud.query("articles", { _limit: 300 });
  if (existing.errors) throw new Error(JSON.stringify(existing.errors));
  const known = new Set((existing.data || []).map((row) => row.slug));

  let created = 0;
  for (const article of ARTICLES) {
    if (known.has(article.slug)) {
      console.log("[seed-content] skip article:", article.slug);
      continue;
    }
    const result = await sdk.crud.createRecord("articles", {
      title: article.title,
      slug: article.slug,
      description: article.description,
      content: article.content,
      image_url: article.image_url,
      category: CAT[article.cat],
      language: article.language,
      published: "yes",
    });
    if (result.errors) {
      console.error("[seed-content] article failed:", article.slug, JSON.stringify(result.errors));
      throw new Error("article seed failed");
    }
    created += 1;
    console.log("[seed-content] created article:", article.slug);
  }
  console.log(`[seed-content] articles — ${created} created`);
}

async function seedBanners() {
  const existing = await sdk.crud.query("banners", { _limit: 100 });
  if (existing.errors) throw new Error(JSON.stringify(existing.errors));
  const known = new Set((existing.data || []).map((row) => row.title));

  let created = 0;
  for (const banner of BANNERS) {
    if (known.has(banner.title)) {
      console.log("[seed-content] skip banner:", banner.title);
      continue;
    }
    const result = await sdk.crud.createRecord("banners", banner);
    if (result.errors) {
      console.error("[seed-content] banner failed:", banner.title, JSON.stringify(result.errors));
      throw new Error("banner seed failed");
    }
    created += 1;
    console.log("[seed-content] created banner:", banner.title);
  }
  console.log(`[seed-content] banners — ${created} created`);
}

async function main() {
  await seedArticles();
  await seedBanners();
  console.log("[seed-content] done");
}

main().catch((err) => {
  console.error("[seed-content] fatal:", err);
  process.exit(1);
});
